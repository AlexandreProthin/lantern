import { readFileSync } from 'node:fs';
import { test, expect } from '@playwright/test';
test('UP-3/4/20: General offers the launch-check switch, and the manual check is desktop only', async ({page}) => {
  await page.goto('/?study=1&subject=Updates');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  const dialog=page.getByRole('dialog');
  const launch=dialog.getByRole('checkbox',{name:'Check for updates at launch'});
  await expect(launch).toBeChecked();
  await launch.uncheck();
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('lantern.settings')??'{}').updates?.checkAtLaunch)).toBe(false);
  await expect(dialog.getByRole('button',{name:'Check for updates',exact:true})).toBeDisabled();
  await expect(page.getByText(/is available/)).toHaveCount(0);
});
test('SE-6/14/16/42: validation, scoped reset, provider health and live reduced motion', async ({page}) => {
  await page.goto('/?study=1&subject=Preferences');
  await expect(page.locator('.panel').getByRole('button',{name:'Test me',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  const dialog=page.getByRole('dialog');
  // SE-22: General ends with the app version from package.json.
  const {version}=JSON.parse(readFileSync('package.json','utf8'));
  await expect(dialog.getByText(`Lantern ${version}`,{exact:true})).toBeVisible();
  await dialog.getByRole('button',{name:'Provider',exact:true}).click();
  await expect(dialog.getByRole('status')).toContainText('Signed in · fake-tutor');
  const model=dialog.getByRole('combobox',{name:'Default model'});
  // SE-48: the whole list is offered, whatever the current value.
  await expect(model.locator('option')).toHaveCount(11);
  await model.selectOption('other');
  const custom=dialog.getByRole('textbox',{name:'Default model'});
  await custom.fill('not valid');await custom.press('Enter');
  await expect(dialog.getByRole('alert')).toContainText('1–100');
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('lantern.settings')!).provider.defaultModel)).toBe('opus');
  await custom.fill('claude-opus-4-7');await custom.press('Enter');
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('lantern.settings')!).provider.defaultModel)).toBe('claude-opus-4-7');
  await model.selectOption('claude-sonnet-5-5');
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('lantern.settings')!).provider.defaultModel)).toBe('claude-sonnet-5-5');
  await dialog.getByRole('button',{name:'Reset to defaults',exact:true}).click();
  await expect(dialog.getByText('Reset this section to its defaults?')).toBeVisible();
  await dialog.getByRole('button',{name:'Reset to defaults',exact:true}).click();
  await expect(model).toHaveValue('opus');
  await dialog.getByRole('button',{name:'Learn',exact:true}).click();
  await dialog.getByText('Advanced',{exact:true}).click();
  const budget=dialog.getByRole('spinbutton',{name:'Map context budget'});
  await budget.fill('100');await budget.press('Enter');
  await expect(dialog.getByRole('alert')).toContainText('2000 to 100000');
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('lantern.settings')!).learn.contextBudget)).toBe(12000);
  await dialog.getByRole('button',{name:'Appearance',exact:true}).click();
  await dialog.getByRole('combobox',{name:'Reduce motion'}).selectOption('on');
  await dialog.getByRole('button',{name:'Close',exact:true}).click();
  await expect(page.locator('.graph')).toHaveAttribute('data-reduced','true');
  await page.reload();await page.getByRole('button',{name:'Settings',exact:true}).click();
  await dialog.getByRole('button',{name:'Appearance',exact:true}).click();
  await expect(dialog.getByRole('combobox',{name:'Reduce motion'})).toHaveValue('on');
});
